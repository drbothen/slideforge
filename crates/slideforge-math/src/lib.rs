//! `slideforge-math` — math rendering engine for slideforge.
//!
//! This crate implements the [`MathRenderer`] plugin surface from
//! `slideforge-plugin-api`. It is the built-in LaTeX → OMML/MathML renderer
//! shipped with slideforge.
//!
//! ## Pipeline
//!
//! ```text
//! MathNode (raw LaTeX + span)
//!   └─► substitute()  — @{var} interpolation
//!         └─► parse()    — LaTeX → MathAst
//!               └─► omml::render() / (future: mathml::render())
//!                     └─► Vec<u8>  — OMML or MathML bytes
//! ```
//!
//! ## Supported outputs
//!
//! | Format | Status |
//! |--------|--------|
//! | [`MathOutputFormat::Omml`] | Planned (story STORY-029) |
//! | [`MathOutputFormat::MathMl`] | Not yet implemented |
//! | [`MathOutputFormat::Pdf`] | Not yet implemented |
//!
//! ## Dependency on `pulldown-latex`
//!
//! `pulldown-latex = "0.7.1"` is used for its LaTeX tokenizer to build the
//! [`MathAst`]. The OMML output is generated by our own recursive walker in
//! [`omml`]; the `MathML` path will route through pulldown-latex's native output
//! when implemented.

