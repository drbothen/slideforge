//! `slideforge-math` — math rendering engine for slideforge.
//!
//! This crate implements the [`MathRenderer`] plugin surface from
//! `slideforge-plugin-api`. It is the built-in LaTeX → OMML/MathML renderer
//! shipped with slideforge.
//!
//! ## Pipeline
//!
//! ```text
//! MathNode (raw LaTeX + span)
//!   └─► substitute()  — @{var} interpolation
//!         └─► parse()    — LaTeX → MathAst
//!               └─► omml::render() / mathml::render_mathml() / pdf_paths::render_pdf_paths()
//!                     └─► Vec<u8>  — OMML, MathML, or SVG path bytes
//! ```
//!
//! ## Supported outputs
//!
//! | Format | Status |
//! |--------|--------|
//! | [`MathOutputFormat::Omml`] | Implemented (STORY-029) |
//! | [`MathOutputFormat::MathMl`] | Implemented (STORY-030) |
//! | [`MathOutputFormat::Pdf`] | Implemented (STORY-030) |
//!
//! ## Implementation approach
//!
//! The [`parser`] module is a hand-written recursive-descent parser that
//! converts the supported LaTeX subset directly to [`MathAst`]. The OMML
//! output is generated by our own recursive walker in [`omml`]. The `MathML`
//! path lives in [`mathml`] and the PDF vector-path renderer lives in
//! [`pdf_paths`]; both are implemented in STORY-030.
//! `pulldown-latex` is NOT a dependency — v1.0 uses only the supported subset
//! defined by the behavioral contracts.

